export type Message = keyof typeof russian

export function translate(language: Language, key: Message, ...values: unknown[]): string {
  const pattern = language === 'ru' ? russian[key] : key
  return pattern.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)]))
}
